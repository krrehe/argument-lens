/**
 * 理论透镜注册表。
 *
 * 为什么要有这个文件
 * ------------------
 * 「谬误是什么」在学科内部没有公认答案。SEP《Fallacies》把标准定义
 * （看似有效而实际无效）拆成三个必要条件，然后说「All three conditions
 * have been brought into question」。分类学至少五套且互不兼容。
 *
 * 所以本应用不假装有唯一正确的分析口径。它让用户选一副透镜，
 * 并如实告诉用户：换一副透镜，同一个地方会被判成不同的东西。
 *
 * 这不是功能上的妥协，是这类工具唯一诚实的存在方式。
 *
 * 六副透镜的共同点：都能归结为「一组检查项 + 每一项的回答」。
 * 差别在于「问什么」「问到多细」「答完怎么算」。
 */

export type TheoryId = 'walton' | 'pragma' | 'ars' | 'pta' | 'toulmin' | 'copi';

export interface TheoryProfile {
  id: TheoryId;
  /** 界面显示名 */
  name: string;
  nameEn: string;
  /** 标签页上的短名，≤6 字 */
  short: string;

  /** 地形图上的点标签，≤4 字。图上空间只有 300px，这里必须极短。 */
  tiny: string;

  /** 这套理论认为「论证出错」是什么。一句话，是整个透镜的世界观。 */
  claim: string;

  /**
   * `claim` 的大白话版。同一个意思，不用一个术语。
   *
   * 为什么要单独存一份而不是让界面自动改写：自动改写出来的「通俗版」通常是
   * 把术语换成近义词，读者照样不懂。人话版必须重写句子结构，这只能手写。
   */
  plainClaim: string;

  /** 判定单元：一次判断落在什么东西上 */
  unit: string;

  /** `unit` 的大白话版 */
  plainUnit: string;

  /** 原生刻度：这套理论自己的评级词汇，不是我们归一化的那套 */
  scale: string;

  /**
   * 在「六透镜地形图」上的坐标。0–1。
   * x：看单个论证（0）↔ 看整场讨论（1）
   * y：给结构（0）↔ 给名称（1）
   *
   * 坐标是手填的，不是算出来的。它的用途不是精确，是让用户一眼看出
   * 这六副透镜不是六个同质选项，而是占据了不同的位置。
   */
  map: { x: number; y: number };

  /** 为什么它落在这个位置。一句话，图上悬停可见。 */
  mapNote: string;

  /** 判定流程，界面按此渲染步骤条 */
  procedure: string[];

  /** 什么时候该用它 */
  appliesWhen: string[];

  /** 什么时候它必然失效。每副透镜都必须自带这一栏。 */
  failsWhen: string[];

  /** 常驻提醒，显示在结果页顶部 */
  caveat: string;

  /** 理论出处 */
  source: string;

  /** 归一化刻度在这副透镜下的具体含义，避免用户误读通用的三档 */
  levelMeaning: {
    withstands: string;
    weakened: string;
    fails: string;
  };
}

