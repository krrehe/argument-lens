import type { TheoryId } from './theories';

/**
 * 理论卡：每副透镜背后的争议。
 *
 * 为什么需要这个东西：`theories.ts` 里的 `claim` 说的是「这套理论认为什么」，
 * 但它不说「凭什么」。用户读完一份判定，最自然会问的一句是「你凭什么这么说」。
 * 只答「沃尔顿说的」，是把权威当理由——而这个工具反对的正是这件事。
 *
 * 所以每张卡有四栏：
 *   ground      这个主张的根据是什么（不是谁说的，是它的道理）
 *   objections  谁反对它、反对什么、这套理论怎么回应（回应不了的就写回应不了）
 *   blind       它测不出什么（承认盲区比宣称全面更可信）
 *   refs        可核查的一手文献
 *
 * 写作纪律：objections 里不许出现我没把握的人名与年份。
 * 有具体出处的写具体，只有一般性反对的写「常见反对」，不编引用。
 */

export interface TheoryObjection {
  /** 提出方：具体学者，或「常见反对」这类一般性表述 */
  who: string;
  /** 反对什么 */
  what: string;
  /** 这套理论的回应；回应不了就照实写 */
  answer: string;
}

export interface TheoryNote {
  ground: string;
  objections: TheoryObjection[];
  blind: string[];
  refs: string[];
}

