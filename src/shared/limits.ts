/**
 * 三类：只有一把尺子。
 *
 * 这一组是立场，不是能力。工具在这里**有**选择，只是选择只有一种——
 * 把它写成「客观」才是最不诚实的那种写法。
 */
const NORM: LimitGroup = {
  id: 'norm',
  title: '它只有一套规范',
  gist: '分析传统下的非形式逻辑与论辩理论。不按领域切换、不按文化传统切换、不声明自己的视角。',
  notes: [
    {
      claimId: 'T8-12',
      text: '它不按领域换标准：同一套规范对所有文本。专题分析只列出该领域该问的问题，不改阈值——批判性思维能不能跨领域迁移，学界本身没有共识。',
    },
    {
      claimId: 'T9-08',
      text: '它不按文化传统切换标准。「兼容多元传统」这句话很好听，但它做不到，写出来就等于把局限盖过去。',
    },
    {
      claimId: 'T9-07',
      text: '它不声明自己的视角，报告里没有「从某某立场看」这一栏。理由是：一句不可核的视角声明，比沉默更像是在处理问题。代价是沉默会被读成默认立场——这一点它承认，但不假装解决了。',
    },
    {
      claimId: 'T10-06',
      text: '它没有因明这一套。因明的喻支要求举出同品与异品的实例，而一段文本看不出说话者愿意把哪些算作同类——这一支读不出来，所以不硬做。遇到汉传佛教论式，它会被套进图尔敏，那是范畴错误。',
    },
  ],
};

const GROUPS: LimitGroup[] = [OBJECT, DEPTH, NORM];

/**
 * 本次特有的边界。空数组也是正常结果——
 * 不是每次分析都要凑出一条「本次特别要注意」的话。
 */
function ofThis(d: Diagnosis): LimitNote[] {
  const out: LimitNote[] = [];
  const mode = normalizeMode(d.mode);

  if (!MODE_META[mode].givesVerdict) {
    out.push({
      claimId: 'T8-08',
      text: `本次是${MODE_META[mode].label}模式：不给判定档位，档位一律「未定」。这不是省略，是设计——批判不等于否定，先看清结构再谈好坏。`,
    });
  }

  if (!d.context.opposingPosition) {
    out.push({
      claimId: 'T4-05',
      text: '本次没识别出对手方：独白文本里没有「对方」，要靠对方才成立的几条规则无从违反。这部分照实打折，不靠默认值补上。',
    });
  }

  if (!d.scope.applicable) {
    out.push({
      claimId: 'T1-02',
      text: '本次判成「不适用这套透镜」：检查项因此为空。空报告优于假报告——凑满检查项的分析通常是在编。',
    });
  }

  return out;
}

export function limitsOf(d: Diagnosis): LimitView {
  const thisRun = ofThis(d);
  const always = GROUPS.reduce((n, g) => n + g.notes.length, 0);
  return { thisRun, groups: GROUPS, total: thisRun.length + always };
}

/** 恒定边界里出现的全部主张 id。检查器按它核对覆盖，UI 不必关心。 */
export const LIMIT_CLAIM_IDS: string[] = GROUPS.flatMap((g) => g.notes.map((n) => n.claimId));
