/**
 * 示例文本库。
 *
 * 为什么是一组而不是一段。
 *
 * 原来只有一段（第 0 段，校园早读那段），按「填入示例」永远填同一段。
 * 后果在存档里看得见：一百多份报告里绝大多数是同一段文本——
 * **那不是一百个样本，是同一个样本跑了一百遍。** 它证明的是软件稳定，不是判断准。
 * 而按钮本身在教人这么用：想再试一次，按它就又得到同一段。
 *
 * 所以这里放六段不同体裁、不同毛病的文本，每按一次换下一段。
 * 体裁标出来是有用的：它同时回答「这类话也算论证吗」——
 * 社论、带货、研究摘要、职场、养生帖都算，这正是这个工具的用武之地。
 *
 * 两条硬约束：
 *
 * 1. **第 0 段一个字都不能改。** 它是历史存档、假模型夹具
 *    （`scripts/mock-llm.mjs`、`mock-data.ts`）共同依赖的那段原文：
 *    落点图的 span 是照着它现算出来的，冒烟断言的「有命中」也挂在上面。
 *    改了它，那些断言会变成在验另一段文字，而它们不会报错——只会静默地验错东西。
 *    这条由 `scripts/check-samples.ts` 用指纹钉住。
 * 2. **每段要真的能被判。** 写得像论证，才有东西可拆；
 *    故意写成纯事实陈述的话，用户第一次用就会以为这工具坏了。
 *
 * 六段各埋一种典型毛病，覆盖不同的裁决路径（因果、诉诸权威、以偏概全、
 * 假二难、个案代统计、诉诸传统），这样连按六次能看到六种不同的报告形态。
 */

export interface Sample {
  /** 体裁名。显示在提示里，也用来告诉用户「什么样的文字值得拿来判」 */
  genre: string;
  /** 这段最适合先问哪一类问题（只是建议，用户随时可以换模式） */
  hint: string;
  text: string;
}

