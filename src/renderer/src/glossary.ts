/**
 * 术语表。
 *
 * 存在的理由很简单：这个应用里的每个词都是学科黑话。
 * 「担保」「型式」「可接受性」——写出这些词的人省了事，读的人多花三分钟，
 * 而那三分钟恰好是他决定要不要继续用这个软件的三分钟。
 *
 * 所以每个术语必须同时有两样东西：
 *   plain —— 一句人话，不许再出现任何术语，读完就懂
 *   more  —— 为什么它要单独成一个概念（可选，给想深一层的人）
 *   eg    —— 一个具体例子（可选）
 *
 * 界面上的用法是 <Term k="warrant">担保</Term>，鼠标停上去出提示。
 */

