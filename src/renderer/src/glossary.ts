export const GLOSSARY_LIST = G;

export const GLOSSARY: Record<string, GlossaryEntry> = Object.fromEntries(G.map((e) => [e.k, e]));

export const GLOSSARY_GROUPS: { name: string; items: GlossaryEntry[] }[] = (() => {
  const order: string[] = [];
  const map = new Map<string, GlossaryEntry[]>();
  for (const e of G) {
    if (!map.has(e.group)) {
      map.set(e.group, []);
      order.push(e.group);
    }
    map.get(e.group)!.push(e);
  }
  return order.map((name) => ({ name, items: map.get(name)! }));
})();
