/**
 * 透镜二：语用辩证十规则。
 *
 * 理论主张：论证出错，是某个言语行为违反了使批判性讨论得以进行的规则，
 * 从而阻碍了分歧的解决。谬误 = 规则违反，不需要先命名。
 *
 * 出处：van Eemeren & Grootendorst，十规则。
 *
 * 这副透镜的优点是可执行：十条祈使句，每条对应一类违规，判定形式是
 * 「第 4 条被违反，因为用了与结论无关的理由」——不要求先给名字。
 * 缺点是适用范围窄：只在说话人确实以解决分歧为目标时成立。
 */

