/**
 * 评测语料：28 段真实体裁的论证文本，埋了 18 类毛病。
 *
 * 这不是「测试用例」，是**样本**。区别在于：测试用例断言输出等于某个值，
 * 样本只记录「这段文本里埋了什么」，以及「一个够好的分析必须接住哪几处」。
 * 模型的输出每次都不一样，写死断言只能测出「今天和昨天不一样」。
 *
 * 每条样本的设计原则：
 *   1. 埋在里面的东西是真的（引文、数字、逻辑跳跃都在原文里，不是我编的评语）。
 *   2. 至少有一处**容易判错**的地方，且我知道正确答案长什么样。
 *   3. 体裁不重复：学术摘要、哲学短文、判决理由、广告、新闻转述、伪科普、
 *      非论证描写、议价对话、强论证、引用密集段、工程决策、长社论、英文评论、
 *      数学证明、引述反驳、政策简报、会议纪要、个人陈述、评论片段、网络评论、
 *      会诊记录、历史论证、研究评论、医院质控年报、合同条款、项目复盘、
 *      学术评审意见、增长实验报告。
 *
 * 每条带 expect，是给 audit.ts 用的机器可检项。expect 只写我有把握的，
 * 不确定的不写——写上去就是把我的猜测当成标准答案去量模型。
 *
 * 每段还带毛病类型（见 `kinds.ts` 的 KINDS_BY_CASE）。类型的作用不是分类学，
 * 是回答一个具体问题：**这类毛病是不是只有一段文本在考**——只有一段，
 * 就分不清「软件抓到了这类毛病」和「软件认出了这段文本的写法」。`check:corpus` 守着这件事。
 */
import type { AnalysisMode, DialogueType, TheoryId, VerdictLevel } from '@shared/types';

export interface EvalCase {
  id: string;
  title: string;
  /** 体裁。用来分组看「哪类文本最容易被分析坏」 */
  genre: string;
  theory: TheoryId;
  mode: AnalysisMode;
  /** 这段文本里埋了什么。给审计报告当人读的对照 */
  traps: string[];
  expect: {
    /** 范围门期望。非论证文本必须为 false */
    scopeApplicable?: boolean;
    /** 对话类型期望（只有一个正确答案时用它） */
    dialogueType?: DialogueType;
    /** 对话类型期望（几种读法都站得住时用它，别把可辩护的差异报成错） */
    dialogueTypeAny?: DialogueType[];
    /** 至少抽出几条主张（结论也算一条） */
    minClaims?: number;
    /** 最多几条。非论证文本用 0——多抽一条就是凭空造出主张 */
    maxClaims?: number;
    /** 至少要接住其中一条（同义词任一命中即可） */
    mustCatch?: string[];
    /** 这些词不该作为「谬误名」出现在命名候选里 */
    mustNotName?: string[];
    /** 档位不该等于这些值 */
    levelNot?: VerdictLevel[];
    /** 至少几条检查项 */
    minChecks?: number;
    /** 重构模式：必须把读法分歧写进 selfCheck.unknowns */
    unknownsNonEmpty?: boolean;
  };
  text: string;
}

